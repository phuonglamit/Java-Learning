public class D07E02Ex1 {
    public static void main(String[] args) {
        /* 
         * Tính tổng các số chẵn từ 0 đến 10
         */
        int i;
        int tong = 0;
        for (i = 0; i <= 10; i+=2){
            tong+=i; // tong = tong + i

        }
        System.out.println(tong);
    }
    
}
